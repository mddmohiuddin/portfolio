/**
 * Generates an inline SVG sprite for the Lucide icons this site actually uses,
 * and rewrites `<i data-lucide="…">` placeholders in index.html into <svg><use>.
 *
 * Why: the site used to pull lucide@latest from unpkg (368 KB of JS, unpinned,
 * render-blocking) just to draw ~27 icons. The sprite is a few KB, needs no JS
 * and works offline.
 *
 * Run: node scripts/build-icons.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { icons } = require('lucide');

const FILES = ['index.html', '404.html'];

const pascal = (s) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

function findIcon(name) {
  const key = pascal(name);
  return icons[key] || icons[key.replace(/[0-9]+$/, '')] || null;
}

function toSymbol(name, nodes) {
  const body = nodes
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .map(([k, v]) => `${k}="${String(v).replace(/"/g, '&quot;')}"`)
        .join(' ');
      return `<${tag} ${a}/>`;
    })
    .join('');
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`;
}

const I_PATTERN = /<i\s+data-lucide="([^"]+)"([^>]*)><\/i>/g;
// Already-converted markup still tells us which symbols the sprite needs.
const USE_PATTERN = /<use href="#i-([^"]+)"\/>/g;

let used = new Set();
const processed = [];

for (const file of FILES) {
  let html;
  try {
    html = await readFile(file, 'utf8');
  } catch {
    continue; // file may not exist yet
  }
  for (const m of html.matchAll(USE_PATTERN)) used.add(m[1]);
  if (!html.includes('data-lucide')) {
    processed.push(file);
    continue;
  }
  html = html.replace(I_PATTERN, (_m, name, rest) => {
    used.add(name);
    const cls = /class="([^"]*)"/.exec(rest);
    const clsAttr = cls ? ` class="${cls[1]}"` : '';
    return (
      `<svg${clsAttr} viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
      `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">` +
      `<use href="#i-${name}"/></svg>`
    );
  });
  await writeFile(file, html);
  processed.push(file);
}

const symbols = [];
const missing = [];
for (const name of [...used].sort()) {
  const nodes = findIcon(name);
  if (!nodes) {
    missing.push(name);
    continue;
  }
  symbols.push(toSymbol(name, nodes));
}

console.log(`processed: ${processed.join(', ')}`);
console.log(`icons in sprite: ${symbols.length}`);
if (missing.length) console.log(`MISSING from lucide (left as <i>): ${missing.join(', ')}`);

// The sprite is injected into index.html between these markers by the
// vendor step; keep it in its own file so it can be regenerated safely.
if (symbols.length) {
  await writeFile(
    'src/_sprite.html',
    `<!-- Generated by scripts/build-icons.mjs — do not edit by hand -->\n` +
      `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false" ` +
      `style="position:absolute;width:0;height:0;overflow:hidden">\n${symbols.join('\n')}\n</svg>\n`
  );
  console.log('sprite written to src/_sprite.html');
}
